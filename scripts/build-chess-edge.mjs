// Ship the same chess rules and service exercised by the Node tests.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const destination = 'supabase/functions/chess';
await mkdir(destination, { recursive: true });
const bundled = [];
for (const name of ['engine', 'service', 'supabase-storage', 'http']) {
  let code = await readFile(`api/src/chess/${name}.js`, 'utf8');
  code = code.replace("const { Chess } = require('chess.js');", "import { Chess } from 'npm:chess.js@1.4.0';")
    .replace(/const (\{[^\n]+\}) = require\('node:crypto'\);/g, "import $1 from 'node:crypto';")
    .replace("const engine = require('./engine.js');", "import * as engine from './engine.js';")
    .replace(/module.exports\s*=\s*\{([^}]+)\};/g, 'export {$1};');
  if (/require\(|module\.exports/.test(code)) throw new Error(`Unconverted dependency in ${name}`);
  await writeFile(`${destination}/${name}.js`, '// Generated by scripts/build-chess-edge.mjs; edit api/src/chess instead.\n' + code);
  bundled.push(code.replace(/^import .*;\n/gm, '').replace(/^export \{[^\n]+\};\n?/gm, '') + (name === 'engine' ? '\nconst engine = { fail, nameOf, handicapFen, createRoom, gameOf, joinRoom, playerOf, tick, applyCommand, publicView };\n' : ''));
}
if (process.argv.includes('--dashboard')) await writeFile('/tmp/chess-room-deploy.ts', "// Generated from the tested api/src/chess sources.\nimport { Chess } from 'npm:chess.js@1.4.0';\nimport { createHash } from 'node:crypto';\n" + bundled.join('\n') + "\nDeno.serve(makeHandler(new ChessService(new SupabaseRoomStore(Deno.env.get('SUPABASE_URL'), Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')))));\n");
