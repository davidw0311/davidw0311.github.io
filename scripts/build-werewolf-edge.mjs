// Generate deployable ESM from the exact CommonJS modules exercised by API tests.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const directory='supabase/functions/werewolf';
await mkdir(directory,{recursive:true});
for(const name of ['engine','service','supabase-storage','http']) {
 let code=await readFile(`api/src/werewolf/${name}.js`,'utf8');
 code=code.replace(/const (\{[^\n]+\}) = require\('node:crypto'\);/g,"import $1 from 'node:crypto';")
  .replace(/const (\w+) = require\('(\.\/[^']+\.json)'\);/g,"import $1 from '$2' with {type:'json'};")
  .replace("const engine = require('./engine.js');","import * as engine from './engine.js';")
  .replace(/module.exports\s*=\s*\{([^}]+)\};/g,'export {$1};');
 if(/require\(|module\.exports/.test(code)) throw new Error(`Unconverted dependency in ${name}`);
 await writeFile(`${directory}/${name}.js`,'// Generated by scripts/build-werewolf-edge.mjs; edit api/src/werewolf instead.\n'+code);
}
for(const name of ['roles.json','room-words.json']) await writeFile(`${directory}/${name}`,await readFile(`api/src/werewolf/${name}`));
