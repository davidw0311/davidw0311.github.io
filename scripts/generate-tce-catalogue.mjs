import { readFileSync, writeFileSync } from 'node:fs';

// Source manifest and optimized images are audited together; this step builds the typed picker data.
const manifest = JSON.parse(readFileSync(new URL('../public/assets/infinite-granite/tce/catalogue.json', import.meta.url), 'utf8'));
const products = manifest.products.map(product => ({
  id: product.id,
  company: product.company,
  code: product.supplierCode,
  name: product.name,
  family: product.material,
  color: product.baseColor,
  pattern: product.style === 'Speckled' ? 'speckle' : product.style === 'Solid' ? 'cloud' : 'vein',
  vein: '#aaaaaa',
  note: `${product.finish} · ${product.slabSize}`,
  roughness: product.roughness,
  textureUrl: product.textureUrl,
  thumbnailUrl: product.thumbnailUrl,
  textureWidth: product.textureWidth,
  textureHeight: product.textureHeight,
  sourceUrl: product.sourceUrl,
  ...(product.discontinued || product.clearance ? { availability: product.availability } : {}),
  textureKind: product.textureSourceType === 'full-slab' ? 'slab' : 'detail',
}));
writeFileSync(new URL('../app/projects/infinite-granite/tceStone.ts', import.meta.url),
  `// Generated by scripts/generate-tce-catalogue.mjs from the audited official catalogue.\n// Product sources and photography attribution: public/assets/infinite-granite/tce/catalogue.json\nimport type { CountertopMaterial } from './materials.ts';\n\nexport const tceStoneMaterials: CountertopMaterial[] = ${JSON.stringify(products, null, 2)};\n`);
console.log(`Generated ${products.length} TCE Stone materials.`);
