// Bundle the same source files that the Node test suite exercises for Deno.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
const source = 'api/src/one-night';
const destination = 'supabase/functions/one-night';
await mkdir(destination, { recursive: true });
for (const name of await readdir(source)) {
  if (name.endsWith('.json')) {
    await writeFile(`${destination}/${name}`, await readFile(`${source}/${name}`));
    if (name.endsWith('-roles.json')) await writeFile(`public/assets/one-night/${name}`, await readFile(`${source}/${name}`));
    continue;
  }
  if (!name.endsWith('.js')) continue;
  let code = await readFile(`${source}/${name}`, 'utf8');
  code = code.replace(/const (\{[^;]+?\})\s*=\s*require\(['"]([^'"]+)['"]\);/g, "import $1 from '$2';")
    .replace(/const (\w+)\s*=\s*require\(['"](\.\/[^'"]+\.json)['"]\);/g, "import $1 from '$2' with {type:'json'};")
    .replace(/const (\w+)\s*=\s*require\(['"](\.\/[^'"]+\.js)['"]\);/g, "import * as $1 from '$2';")
    .replace(/module.exports\s*=\s*\{([^}]+)\};/g, (_match, values) =>
      `export {${values.split(',').map(value => value.includes(':') ? value.split(':').reverse().map(x=>x.trim()).join(' as ') : value).join(',')}};`);
  if (/require\(|module\.exports/.test(code)) throw new Error(`Unconverted dependency: ${name}`);
  await writeFile(`${destination}/${name}`, '// Generated by scripts/build-one-night-edge.mjs. Edit api/src/one-night instead.\n' + code);
}
